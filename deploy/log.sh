#!/usr/bin/env bash
# Writes deploy/DEPLOYMENTS.md: every server (who it's for, domain, droplet), every deploy to it
# (when, which apps, which changes) and what is still waiting to go there. Built from
# deploy/servers.info and git (release lines and their tags), so it can't drift from what ran.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
OUT=deploy/DEPLOYMENTS.md
INFO=deploy/servers.info
field() { awk -F'|' -v n="$1" -v i="$2" '!/^#/ && NF { gsub(/^ +| +$/, "", $1); if ($1 == n) { gsub(/^ +| +$/, "", $i); print $i } }' "$INFO"; }
servers() { awk '!/^#/ && NF {print $1}' deploy/servers.conf; }
app_of_path() { case "$1" in web/*) echo web ;; apps/workspace/*) echo workspace ;; esac; }
# A change on a release line is a cherry-pick of a main commit: show main's hash and subject.
change() { local h=$1 orig; orig=$(git log -1 --format=%B "$h" | sed -n 's/^(cherry picked from commit \([0-9a-f]*\))$/\1/p' | tail -1); echo "${orig:0:7}|$(git log -1 --format=%s "$h")"; }

{
  echo "# Deployments"
  echo
  echo "_Generated by \`deploy/ship.sh log\` (and after every deploy) from \`deploy/servers.info\` and git. Edit servers.info, not this file. Last written $(date '+%Y-%m-%d %H:%M %Z')._"
  echo
  echo "## Servers"
  echo
  echo "| Server | For | Domain | Droplet | Region | Size | Switched off | Live since | Now on |"
  echo "|---|---|---|---|---|---|---|---|---|"
  for s in $(servers); do
    now=$(git describe --tags --abbrev=0 --match "$s/*" "origin/release/$s" 2>/dev/null || echo "not deployed yet")
    echo "| **$s** | $(field "$s" 2) | $(field "$s" 3) | $(field "$s" 4) | $(field "$s" 5) | $(field "$s" 6) | $(field "$s" 7) | $(field "$s" 8) | \`$now\` |"
  done
  echo
  for s in $(servers); do
    echo "## $s: $(field "$s" 3)"
    note=$(field "$s" 9); [ -n "$note" ] && echo && echo "$note."
    echo
    echo "### Waiting to go to $s"
    echo
    p=$(git log --no-merges --cherry-pick --right-only --reverse --format='%h|%ad|%s' --date=short "origin/release/$s...origin/main" -- web apps/workspace 2>/dev/null || true)
    if [ -z "$p" ]; then echo "Nothing: $s has every change on main."; else
      echo "$p" | while IFS='|' read -r h d sub; do echo "- \`$h\` $d $sub"; done
    fi
    echo
    echo "### Deploy history (newest first)"
    echo
    tags=$(git tag --list "$s/*" --sort=-creatordate)
    [ -n "$tags" ] || echo "No deploys yet."
    for t in $tags; do
      prev=$(git describe --tags --abbrev=0 --match "$s/*" "$t^" 2>/dev/null || true)
      range=${prev:+$prev..}$t
      when=$(git log -1 --format='%ad' --date=format:'%Y-%m-%d %H:%M' "$t")
      apps=$(git diff --name-only ${prev:-$(git rev-list --max-parents=0 "$t" | tail -1)} "$t" 2>/dev/null | while read -r f; do app_of_path "$f"; done | sort -u | tr '\n' ' ')
      echo "**\`$t\`** · $when · apps: ${apps:-none}"
      echo
      if [ -z "$prev" ]; then echo "- First deploy: everything on the line up to $(git log -1 --format='%h %s' "$t")"; else
        git log --no-merges --reverse --format=%h "$range" -- web apps/workspace | while read -r h; do
          c=$(change "$h"); echo "- \`${c%%|*}\` ${c#*|}"
        done
        [ -n "$(git log --no-merges --format=%h "$range" -- web apps/workspace)" ] || echo "- Redeploy of the same code"
      fi
      echo
    done
  done
} > "$OUT"
echo "✓ wrote $OUT"
